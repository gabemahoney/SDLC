#!/usr/bin/env python3
"""Render Apiary's agents/*.md as Codex CLI custom agents, and lint the result.

  python3 scripts/codex_agents.py render --out ~/.codex/agents [--dry-run]
  python3 scripts/codex_agents.py lint <dir>

render writes one <name>.toml per agents/apiary-*.md: name, description,
model and model_reasoning_effort (from the model map below) and
developer_instructions (the Markdown body plus generated Codex CLI notes).
It writes each file in place and touches nothing else in --out.

lint parses every apiary-*.toml in <dir> with tomllib (Python 3.11+) or
tomli, and checks the keys. It exits 2 when neither parser is available.

Python 3 standard library only; rendering needs no TOML parser.
"""

import argparse
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
AGENTS_DIR = REPO / "agents"

# Claude model -> Codex model. A Claude model containing the key gets the
# value; anything else gets no model line (Codex's default). Override with
# APIARY_CODEX_MODEL_OPUS, _SONNET or _HAIKU; an empty value means no model line.
MODEL_MAP = {"opus": "gpt-6-astra", "sonnet": "gpt-6.1-sol", "haiku": "gpt-6-luna"}
EFFORTS = ("low", "medium", "high", "xhigh", "max")
WRITE_TOOLS = {"Edit", "Write"}

CODEX_NOTES = """\
## Codex CLI notes

Generated by Apiary's installer for Codex CLI. They say how to read the instructions above in Codex.

- You are a Codex CLI agent running an assignment from an Apiary skill. Your final message is your report to the calling agent.
- "Invoke the /x skill", "use the x skill" or the Skill tool means: read `~/.agents/skills/x/SKILL.md` (or the repo's `.agents/skills/x/SKILL.md`) and follow it.
- CLAUDE.md means the repo's `CLAUDE.md` file. Codex does not load it for you: read it yourself from the repo root.
"""

READ_ONLY_NOTE = """\
- This agent does not edit files: never use apply_patch or write files with shell commands. The bees CLI is allowed where these instructions use it (a ticket body may go through a temporary file outside the repo).
"""


class RenderError(Exception):
    pass


def model_map():
    out = {}
    for key, default in MODEL_MAP.items():
        out[key] = os.environ.get("APIARY_CODEX_MODEL_" + key.upper(), default)
    return out


def parse_agent(path):
    """Return (front matter dict, body) of an agent definition."""
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise RenderError(f"{path}: no front matter")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise RenderError(f"{path}: front matter is not closed")
    meta = {}
    for line in lines[1:end]:
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise RenderError(f"{path}: bad front matter line: {line!r}")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[key.strip()] = value
    body = "\n".join(lines[end + 1:]).strip("\n") + "\n"
    return meta, body


def basic_string(value):
    """A TOML basic string."""
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def literal_block(value, where):
    """A TOML multi-line literal string; refuses what one cannot hold."""
    if "'''" in value:
        raise RenderError(f"{where}: the body contains ''' and cannot be a TOML literal string")
    for ch in value:
        if (ord(ch) < 0x20 and ch not in "\n\t") or ord(ch) == 0x7F:
            raise RenderError(f"{where}: the body contains control character U+{ord(ch):04X}")
    if not value.endswith("\n"):
        value += "\n"
    return "'''\n" + value + "'''"


def codex_model(claude_model, models):
    name = claude_model.lower()
    for key, value in models.items():
        if key in name:
            return value or None
    return None


def instructions(meta, body):
    tools = {t.strip() for t in meta.get("tools", "").split(",") if t.strip()}
    notes = CODEX_NOTES
    if not tools & WRITE_TOOLS:
        notes += READ_ONLY_NOTE
    return body.rstrip("\n") + "\n\n" + notes


def render_one(path, models):
    meta, body = parse_agent(path)
    for key in ("name", "description"):
        if not meta.get(key):
            raise RenderError(f"{path}: front matter has no {key}")
    if meta["name"] != path.stem:
        raise RenderError(f"{path}: name {meta['name']!r} differs from the file name")
    if not body.strip():
        raise RenderError(f"{path}: empty body")
    lines = [
        f"# Generated from agents/{path.name} by Apiary's installer (scripts/codex_agents.py).",
        "# Do not edit: edit the .md file and re-run ./install.sh --agent codex.",
        f"name = {basic_string(meta['name'])}",
        f"description = {basic_string(meta['description'])}",
    ]
    model = codex_model(meta.get("model", ""), models)
    if model:
        lines.append(f"model = {basic_string(model)}")
    effort = meta.get("effort", "")
    if effort:
        if effort not in EFFORTS:
            raise RenderError(f"{path}: effort {effort!r} is not one of {', '.join(EFFORTS)}")
        lines.append(f"model_reasoning_effort = {basic_string(effort)}")
    lines.append("developer_instructions = " + literal_block(instructions(meta, body), str(path)))
    return meta["name"], "\n".join(lines) + "\n"


def toml_parser():
    try:
        import tomllib  # Python 3.11+
        return tomllib
    except ImportError:
        pass
    try:
        import tomli
        return tomli
    except ImportError:
        return None


def lint_text(parser, stem, text, models):
    """Return a list of problems with one rendered agent."""
    try:
        data = parser.loads(text)
    except Exception as exc:  # the parser's own error type
        return [f"does not parse: {exc}"]
    problems = []
    for key in ("name", "description", "developer_instructions"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            problems.append(f"{key} is missing or blank")
    if data.get("name") != stem:
        problems.append(f"name {data.get('name')!r} differs from the file name {stem!r}")
    allowed = {m for m in models.values() if m}
    if "model" in data and data["model"] not in allowed:
        problems.append(f"model {data['model']!r} is not one of {sorted(allowed)}")
    if "model_reasoning_effort" in data and data["model_reasoning_effort"] not in EFFORTS:
        problems.append(f"model_reasoning_effort {data['model_reasoning_effort']!r} is not one of {EFFORTS}")
    source = AGENTS_DIR / f"{stem}.md"
    if source.is_file() and isinstance(data.get("developer_instructions"), str):
        _, body = parse_agent(source)
        if body.strip() not in data["developer_instructions"]:
            problems.append(f"developer_instructions does not hold the whole body of agents/{source.name}")
    return problems


def cmd_render(args):
    models = model_map()
    sources = sorted(AGENTS_DIR.glob("apiary-*.md"))
    if not sources:
        raise RenderError(f"no agents/apiary-*.md under {REPO}")
    rendered = [render_one(path, models) for path in sources]
    parser = toml_parser()
    if parser is None:
        print("codex_agents: lint skipped: no TOML parser (Python 3.11+ tomllib, or tomli)", file=sys.stderr)
    else:
        failed = False
        for name, text in rendered:
            for problem in lint_text(parser, name, text, models):
                print(f"codex_agents: {name}.toml: {problem}", file=sys.stderr)
                failed = True
        if failed:
            return 1
    out = Path(os.path.expanduser(args.out))
    if args.dry_run:
        print(f"would create {out}/ if missing")
    else:
        out.mkdir(parents=True, exist_ok=True)
    for name, text in rendered:
        target = out / f"{name}.toml"
        if args.dry_run:
            print(f"would write {target} ({len(text.encode('utf-8'))} bytes)")
            continue
        # Write in place (truncate and rewrite), never write-temp-then-rename.
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"wrote {target}")
    return 0


def cmd_lint(args):
    parser = toml_parser()
    if parser is None:
        print("codex_agents: cannot lint: no TOML parser (Python 3.11+ tomllib, or pip install tomli)", file=sys.stderr)
        return 2
    folder = Path(os.path.expanduser(args.dir))
    files = sorted(folder.glob("apiary-*.toml"))
    if not files:
        print(f"codex_agents: no apiary-*.toml in {folder}", file=sys.stderr)
        return 1
    models = model_map()
    failed = False
    for path in files:
        for problem in lint_text(parser, path.stem, path.read_text(encoding="utf-8"), models):
            print(f"codex_agents: {path}: {problem}", file=sys.stderr)
            failed = True
    missing = sorted({p.stem for p in AGENTS_DIR.glob("apiary-*.md")} - {p.stem for p in files})
    for stem in missing:
        print(f"codex_agents: {folder}: no {stem}.toml for agents/{stem}.md", file=sys.stderr)
        failed = True
    if failed:
        return 1
    print(f"codex_agents: {len(files)} agents in {folder} pass")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="Render and lint Apiary's Codex CLI agents.")
    sub = ap.add_subparsers(dest="command", required=True)
    render = sub.add_parser("render", help="render agents/*.md into <out>/<name>.toml")
    render.add_argument("--out", required=True, help="target folder, e.g. ~/.codex/agents")
    render.add_argument("--dry-run", action="store_true", help="print what would be written; write nothing")
    lint = sub.add_parser("lint", help="parse and check every apiary-*.toml in a folder")
    lint.add_argument("dir")
    args = ap.parse_args(argv)
    try:
        return cmd_render(args) if args.command == "render" else cmd_lint(args)
    except RenderError as exc:
        print(f"codex_agents: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
